#!/usr/bin/env python3
"""Scan the candidate release for private paths and internal drafting traces."""

from __future__ import annotations

import gzip
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
TEXT_SUFFIXES = {".py", ".md", ".txt", ".json", ".csv", ".toml", ".yml", ".yaml", ".sh"}
FORBIDDEN = {
    "author_identity": re.compile(r"(?i)ran wang|wangran@|hangzhou dianzi|hdu\.edu"),
    "private_windows_path": re.compile(
        r"(?i)[a-z]:(?:\\{1,2}|/{1,2})(?:users|mypaper|home)(?:\\{1,2}|/{1,2})"
    ),
    "private_unix_path": re.compile(r"(?i)/home/(?:icdm|administrator|runner)/"),
    "private_infrastructure": re.compile(r"(?i)server501|inner-direct|ssh\s+inner"),
    "assistant_provenance": re.compile(r"(?i)claude|codex|grok|gemini|chatgpt|openai|anthropic"),
    "conversation_artifact": re.compile(
        r"(?i)as requested by the user|user requested|the user asked|task book|"
        r"producer report|generated by (?:an )?(?:ai|assistant)|as an ai|prompt engineering"
    ),
    "unfinished_comment": re.compile(r"(?im)(?:#|//|/\*)\s*(?:todo|fixme|hack)\b"),
    "revision_comment": re.compile(r"(?i)round\s+\d+\s+(?:fix|repair)|audit\s+fix"),
}


def main() -> None:
    findings: list[str] = []
    for name in ("__pycache__", ".pytest_cache"):
        for path in ROOT.rglob(name):
            findings.append(f"{path.relative_to(ROOT)}: generated cache directory")
    for path in (ROOT / "derived").glob("*"):
        if path.name != ".gitkeep":
            findings.append(f"{path.relative_to(ROOT)}: generated output must not be packaged")
    for path in sorted(ROOT.rglob("*")):
        if path.is_dir() and path.name in {".git", ".pytest_cache", "__pycache__"}:
            continue
        is_gzip_text = path.name.lower().endswith((".csv.gz", ".json.gz", ".txt.gz"))
        if not path.is_file() or (path.suffix.lower() not in TEXT_SUFFIXES and not is_gzip_text):
            continue
        if path.resolve() == Path(__file__).resolve():
            continue
        if any(part in {".git", ".venv", "venv", "__pycache__"} for part in path.parts):
            continue
        try:
            if is_gzip_text:
                with gzip.open(path, "rt", encoding="utf-8") as handle:
                    text = handle.read()
            else:
                text = path.read_text(encoding="utf-8")
        except (UnicodeDecodeError, gzip.BadGzipFile):
            continue
        for label, pattern in FORBIDDEN.items():
            for match in pattern.finditer(text):
                line = text.count("\n", 0, match.start()) + 1
                findings.append(f"{path.relative_to(ROOT)}:{line}: {label}: {match.group(0)!r}")
    if findings:
        raise SystemExit("release scan failed:\n" + "\n".join(findings))
    print("release scan passed")


if __name__ == "__main__":
    main()
